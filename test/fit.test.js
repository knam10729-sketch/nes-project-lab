import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { playLocked, playScrolls } from "../games/fit.js";

test("the play screen locks only while a game is running", () => {
  assert.equal(playLocked("playing"), true);
  assert.equal(playLocked("playing", "mole"), true);
  assert.equal(playLocked("playing", "draw"), false);
  assert.equal(playLocked("playing", "liar"), false);
  assert.equal(playScrolls("draw"), true);
  assert.equal(playScrolls("liar"), true);
  assert.equal(playScrolls("mole"), false);
  assert.equal(playLocked("waiting"), false);
  assert.equal(playLocked("over"), false);
  const css = readFileSync(new URL("../games/games.css", import.meta.url), "utf8");
  assert.match(css, /html\.game-lock[\s\S]*overflow:\s*hidden/);
  assert.match(css, /overscroll-behavior:\s*none/);
  assert.match(css, /100dvh/);
  assert.match(css, /html\.play-scroll[\s\S]*overflow-y:\s*auto/);
  assert.match(css, /--mole-fit:min\(70vw/);
  const client = readFileSync(new URL("../games/client.js", import.meta.url), "utf8");
  assert.match(client, /lockPlay\(playLocked\(state\.status, state\.game\), playScrolls\(state\.game\)\)/);
  assert.equal(client.includes("pinLocalPop"), false);
  const meet = readFileSync(new URL("../games/meet.js", import.meta.url), "utf8");
  assert.equal(meet.includes("lockPlay"), false);
  const fortune = readFileSync(new URL("../games/fortune.js", import.meta.url), "utf8");
  assert.equal(fortune.includes("lockPlay"), false);
  assert.match(fortune, /scrollIntoView/);
  const party = readFileSync(new URL("../games/party.js", import.meta.url), "utf8");
  assert.match(party, /className: "line-form"/);
  assert.equal(party.includes('className: "share"'), false);
});
