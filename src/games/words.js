export function categoryList() {
  return Object.entries(CATEGORIES).map(([id, category]) => ({ id, label: category.label, count: category.words.length }));
}

export function pickWord(categoryId, index) {
  const category = CATEGORIES[categoryId];
  if (!category) return null;
  const words = category.words;
  return { category: category.label, word: words[index % words.length] };
}

export function drawWord(index) {
  return DRAW_WORDS[index % DRAW_WORDS.length];
}

export function choseong(word) {
  const cho = ["ㄱ", "ㄲ", "ㄴ", "ㄷ", "ㄸ", "ㄹ", "ㅁ", "ㅂ", "ㅃ", "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅉ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"];
  return [...word].map((char) => {
    const code = char.charCodeAt(0);
    if (code < 0xac00 || code > 0xd7a3) return char;
    return cho[Math.floor((code - 0xac00) / 588)];
  }).join("");
}
