export function categoryList() {
  return Object.entries(CATEGORIES).map(([id, item]) => ({ id, label: item.label, count: item.words.length }));
}

export function allHints() {
  return Object.assign({}, ...Object.values(CATEGORIES).map((item) => item.hints));
}

export function pickWord(categoryId, index, recent = []) {
  const item = CATEGORIES[categoryId];
  if (!item) return null;
  const words = item.words;
  const blocked = new Set(Array.isArray(recent) ? recent.filter((word) => words.includes(word)) : []);
  const start = Math.abs(Number(index) || 0) % words.length;
  let word = null;
  for (let step = 0; step < words.length; step += 1) {
    const candidate = words[(start + step) % words.length];
    if (!blocked.has(candidate)) {
      word = candidate;
      break;
    }
  }
  if (!word) word = words[start];
  const window = Math.max(1, words.length - 8);
  const nextRecent = [...blocked].filter((past) => past !== word);
  nextRecent.push(word);
  return { category: item.label, word, recent: nextRecent.slice(-window) };
}

